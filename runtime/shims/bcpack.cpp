// Block rebuilders. `lanes` is lane-major with `n` symbols per lane.

int unzig(int v) { return (v & 1) ? -((v + 1) >> 1) : (v >> 1); }

int inter(int a, int b, int n) {
    int d = 0;
    for (int k = 0; k < n; ++k) d |= (((a >> k) & 1) << (2 * k)) | (((b >> k) & 1) << (2 * k + 1));
    return d;
}

int inter8(int a, int b) { return inter(a, b, 4); }

int deint(int s, int odd) {
    return ((s >> odd) & 1) | (((s >> (2 + odd)) & 1) << 1) | (((s >> (4 + odd)) & 1) << 2) |
           (((s >> (6 + odd)) & 1) << 3);
}

struct Lanes {
    const uint16_t* data;
    size_t n;
    const uint16_t* operator[](size_t lane) const { return data + lane * n; }
};

void put_le(uint8_t* out, uint64_t v, int bytes) {
    for (int k = 0; k < bytes; ++k) out[k] = static_cast<uint8_t>(v >> (8 * k));
}

// Four rows of two 3-bit selector pairs each (BC3 alpha, BC4, BC5): 48 bits.
template <typename RowLane>
uint64_t pair_rows(const uint8_t (*pairs)[2], RowLane left_right) {
    uint64_t bits = 0;
    for (int r = 0; r < 4; ++r) {
        const auto [left, right] = left_right(r);
        const uint8_t* lp = pairs[left];
        const uint8_t* rp = pairs[right];
        bits |= uint64_t(lp[0] | (lp[1] << 3) | (rp[0] << 6) | (rp[1] << 9)) << (12 * r);
    }
    return bits;
}

void quadrant_bytes(uint8_t* out, int qa, int qb, int qc, int qd) {
    out[0] = static_cast<uint8_t>((qa & 15) | ((qb & 15) << 4));
    out[1] = static_cast<uint8_t>((qa >> 4) | ((qb >> 4) << 4));
    out[2] = static_cast<uint8_t>((qc & 15) | ((qd & 15) << 4));
    out[3] = static_cast<uint8_t>((qc >> 4) | ((qd >> 4) << 4));
}

const char* class_name(uint8_t cls) { return cls == 1 ? "unconfirmed" : "unknown"; }

// The base of a BC1/BC3/BC4/BC5 block: none, an earlier block, or a built-in history entry. `lost` follows the
// chain so lenient decoding can count every block that rests on an entry that is not confirmed.
template <size_t K>
Status base_of(const char* name, size_t i, int d, const History<K>& history, const std::array<uint8_t, K>& none,
               const std::vector<std::array<uint8_t, K>>& hist, std::vector<uint8_t>& lost, Mode mode, Info* info,
               std::array<uint8_t, K>& base) {
    if (d == 0) {
        base = none;
    } else if (i >= size_t(d)) {
        base = hist[i - d];
        lost[i] = lost[i - d];
    } else {
        const int entry = 256 + static_cast<int>(i) - d;
        const auto& e = history.e[entry];
        if (e.cls == 2) {
            std::copy(e.v, e.v + K, base.begin());
            return Status::ok;
        }
        if (mode == Mode::strict) {
            note(info, "%s block %zu references %s built-in history entry %d", name, i, class_name(e.cls), entry);
            return Status::history;
        }
        note(info, "%s block %zu uses %s built-in history entry %d", name, i, class_name(e.cls), entry);
        if (e.cls == 1) std::copy(e.v, e.v + K, base.begin());
        else base = none;
        lost[i] = 1;
    }
    return Status::ok;
}

bool any_nonzero(const uint16_t* lane, size_t n) {
    for (size_t k = 0; k < n; ++k)
        if (lane[k]) return true;
    return false;
}

size_t count(const std::vector<uint8_t>& flags) {
    size_t n = 0;
    for (uint8_t f : flags) n += f != 0;
    return n;
}

Status bc1_blocks(Lanes lanes, size_t nblocks, uint8_t* out, Mode mode, Info* info) {
    if (any_nonzero(lanes[1], lanes.n)) {
        note(info, "BC1 lane 1 is non-zero (unexpected)");
        return Status::bad_stream;
    }
    static constexpr std::array<uint8_t, 6> kNone{};
    static constexpr int kMods[6] = {32, 64, 32, 32, 64, 32};
    std::vector<std::array<uint8_t, 6>> hist(nblocks);
    std::vector<uint8_t> lost(nblocks, 0);
    const uint16_t* l0 = lanes[0];
    for (size_t i = 0; i < nblocks; ++i) {
        const int v = l0[i];
        const int d = (v & 1) ? 256 - ((v + 1) >> 1) : (v >> 1);
        std::array<uint8_t, 6> base;
        const Status s = base_of("BC1", i, d, kBc1History, kNone, hist, lost, mode, info, base);
        if (s != Status::ok) return s;
        std::array<uint8_t, 6> e;
        for (int k = 0; k < 6; ++k) e[k] = static_cast<uint8_t>((base[k] + unzig(lanes[2 + k][i])) & (kMods[k] - 1));
        hist[i] = e;
        uint8_t* at = out + i * 8;
        put_le(at, (e[0] << 11) | (e[1] << 5) | e[2], 2);
        put_le(at + 2, (e[3] << 11) | (e[4] << 5) | e[5], 2);
        quadrant_bytes(at + 4, kBc1Quadrant[lanes[8][i]], kBc1Quadrant[lanes[9][i]], kBc1Quadrant[lanes[10][i]],
                       kBc1Quadrant[lanes[11][i]]);
    }
    if (info) info->approximated = count(lost);
    return Status::ok;
}

Status bc3_blocks(Lanes lanes, size_t nblocks, uint8_t* out, Mode mode, Info* info) {
    if (any_nonzero(lanes[1], lanes.n)) {
        note(info, "BC3 lane 1 is non-zero (unexpected)");
        return Status::bad_stream;
    }
    static constexpr std::array<uint8_t, 8> kNone{128, 128, 0, 0, 0, 0, 0, 0};
    static constexpr int kMods[8] = {256, 256, 32, 64, 32, 32, 64, 32};
    std::vector<std::array<uint8_t, 8>> hist(nblocks);
    std::vector<uint8_t> lost(nblocks, 0);
    const uint16_t *l0 = lanes[0], *alpha = lanes[2], *lr = lanes[7], *lg = lanes[8], *lb = lanes[9];
    const uint16_t *top = lanes[10], *bottom = lanes[11];
    for (size_t i = 0; i < nblocks; ++i) {
        const size_t a = 2 * i, b = 2 * i + 1;
        const int d = unzig(inter8(l0[a], l0[b])) & 255;
        std::array<uint8_t, 8> base;
        const Status s = base_of("BC3", i, d, kBc3History, kNone, hist, lost, mode, info, base);
        if (s != Status::ok) return s;
        const int dz[8] = {alpha[a], alpha[b], lr[a], lg[a], lb[a], lr[b], lg[b], lb[b]};
        std::array<uint8_t, 8> e;
        for (int k = 0; k < 8; ++k) e[k] = static_cast<uint8_t>((base[k] + unzig(dz[k])) & (kMods[k] - 1));
        hist[i] = e;
        const uint64_t bits = pair_rows(kBc3AlphaPair, [&](int r) {
            return std::pair<int, int>(lanes[3 + r][a], lanes[3 + r][b]);
        });
        uint8_t* at = out + i * 16;
        at[0] = e[0];
        at[1] = e[1];
        put_le(at + 2, bits, 6);
        put_le(at + 8, (e[2] << 11) | (e[3] << 5) | e[4], 2);
        put_le(at + 10, (e[5] << 11) | (e[6] << 5) | e[7], 2);
        quadrant_bytes(at + 12, kBc3ColourQuadrant[top[a]], kBc3ColourQuadrant[top[b]], kBc3ColourQuadrant[bottom[a]],
                       kBc3ColourQuadrant[bottom[b]]);
    }
    if (info) info->approximated = count(lost);
    return Status::ok;
}

Status bc4_blocks(Lanes lanes, size_t nblocks, uint8_t* out, Mode mode, Info* info) {
    if (any_nonzero(lanes[1], lanes.n)) {
        note(info, "BC4 lane 1 is non-zero (unexpected)");
        return Status::bad_stream;
    }
    static constexpr std::array<uint8_t, 2> kNone{128, 128};
    std::vector<std::array<uint8_t, 2>> hist(nblocks);
    std::vector<uint8_t> lost(nblocks, 0);
    const uint16_t *l0 = lanes[0], *l2 = lanes[2], *l3 = lanes[3];
    for (size_t i = 0; i < nblocks; ++i) {
        const int v = l0[i];
        const int d = (v & 1) ? 256 - ((v + 1) >> 1) : (v >> 1);
        std::array<uint8_t, 2> base;
        const Status s = base_of("BC4", i, d, kBc4History, kNone, hist, lost, mode, info, base);
        if (s != Status::ok) return s;
        const std::array<uint8_t, 2> e{static_cast<uint8_t>((base[0] + unzig(l2[i])) & 255),
                                       static_cast<uint8_t>((base[1] + unzig(l3[i])) & 255)};
        hist[i] = e;
        const uint64_t bits = pair_rows(kBc4Pair, [&](int r) {
            return std::pair<int, int>(lanes[4 + 2 * r][i], lanes[5 + 2 * r][i]);
        });
        uint8_t* at = out + i * 8;
        at[0] = e[0];
        at[1] = e[1];
        put_le(at + 2, bits, 6);
    }
    if (info) info->approximated = count(lost);
    return Status::ok;
}

Status bc5_blocks(Lanes lanes, size_t nblocks, uint8_t* out, Mode mode, Info* info) {
    if (any_nonzero(lanes[1], lanes.n)) {
        note(info, "BC5 lane 1 is non-zero (unexpected)");
        return Status::bad_stream;
    }
    static constexpr std::array<uint8_t, 4> kNone{128, 128, 128, 128};
    std::vector<std::array<uint8_t, 4>> hist(nblocks);
    std::vector<uint8_t> lost(nblocks, 0);
    const uint16_t *l0 = lanes[0], *red = lanes[2], *green = lanes[3];
    for (size_t i = 0; i < nblocks; ++i) {
        const size_t a = 2 * i, b = 2 * i + 1;
        const int d = unzig(inter8(l0[a], l0[b])) & 255;
        std::array<uint8_t, 4> base;
        const Status s = base_of("BC5", i, d, kBc5History, kNone, hist, lost, mode, info, base);
        if (s != Status::ok) return s;
        const std::array<uint8_t, 4> e{static_cast<uint8_t>((base[0] + unzig(red[a])) & 255),
                                       static_cast<uint8_t>((base[1] + unzig(red[b])) & 255),
                                       static_cast<uint8_t>((base[2] + unzig(green[a])) & 255),
                                       static_cast<uint8_t>((base[3] + unzig(green[b])) & 255)};
        hist[i] = e;
        uint8_t* at = out + i * 16;
        for (int ch = 0; ch < 2; ++ch) {
            const uint64_t bits = pair_rows(kBc5Pair, [&](int r) {
                return std::pair<int, int>(lanes[4 + 4 * ch + r][a], lanes[4 + 4 * ch + r][b]);
            });
            at[8 * ch] = e[2 * ch];
            at[8 * ch + 1] = e[2 * ch + 1];
            put_le(at + 8 * ch + 2, bits, 6);
        }
    }
    if (info) info->approximated = count(lost);
    return Status::ok;
}

// A 128-bit little-endian block under construction.
struct Bits128 {
    uint64_t w[2] = {0, 0};
    bool put(unsigned pos, uint64_t value, unsigned n) {
        for (unsigned k = 0; k < n; ++k) {
            if (!((value >> k) & 1)) continue;
            const unsigned at = pos + k;
            if (at >= 128) return false;
            w[at >> 6] |= uint64_t(1) << (at & 63);
        }
        return true;
    }
    void store(uint8_t* out) const {
        put_le(out, w[0], 8);
        put_le(out + 8, w[1], 8);
    }
};

