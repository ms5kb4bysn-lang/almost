// ---------------------------------------------------------------------------------------------------------------------
// The rANS models: band frequencies and their running starts.

struct Model {
    int width;
    int64_t freq[kMaxWidth + 1];
    int64_t base[kMaxWidth + 1];
};

struct Models {
    Model m[kMaxWidth + 1][16];
    Models() {
        for (int w = 1; w <= kMaxWidth; ++w)
            for (int q = 0; q < 16; ++q) {
                Model& model = m[w][q];
                model.width = w;
                int64_t acc = 0;
                for (int p = 0; p <= kMaxWidth; ++p) {
                    model.freq[p] = p <= w ? kFreq[w][q][p] : 0;
                    model.base[p] = acc;
                    if (p <= w) acc += model.freq[p] * (p == 0 ? 1 : int64_t(1) << (p - 1));
                }
            }
    }
};

const Models& models() {
    static const Models instance;
    return instance;
}

int bit_length(int64_t v) {
    int n = 0;
    while (v > 0) {
        ++n;
        v >>= 1;
    }
    return n;
}

// The symbol whose slot holds cf, or -1 when its band is empty.
int64_t lookup(const Model& m, int64_t cf) {
    int p = m.width;
    while (p > 0 && cf < m.base[p]) --p;
    if (p == 0) return 0;
    if (m.freq[p] == 0) return -1;
    return (int64_t(1) << (p - 1)) + (cf - m.base[p]) / m.freq[p];
}

int64_t advance(const Model& m, int64_t s, int64_t x) {
    const int p = bit_length(s);
    int64_t f = m.freq[p];
    int64_t c = m.base[p] + f * (s - (p == 0 ? 0 : int64_t(1) << (p - 1)));
    if (c == 0) {
        f -= 1;
        c = 1;
    }
    return f * (x >> 16) + (x & 0xFFFF) - c;
}

